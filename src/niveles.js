/** El tablero abierto del modo clásico. */
const MAPA_CLASICO = (() => {
    const filas = [];
    for (let f = 0; f < FILAS; f++) {
        if (f === 0 || f === FILAS - 1) filas.push('#'.repeat(COLS));
        else filas.push('#' + (f === 8 ? '.....S' + '.'.repeat(COLS - 8) : '.'.repeat(COLS - 2)) + '#');
    }
    return filas;
})();

